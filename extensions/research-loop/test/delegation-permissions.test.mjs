const digest = value => createHash('sha256').update(value).digest('hex');
const write = (file, value) => {
  fs.mkdirSync(path.dirname(file), { recursive: true, mode: 0o700 });
  fs.writeFileSync(file, JSON.stringify(value) + '\n', { mode: 0o600 });
};
function fixture(t, { inheritedReadOnly = false } = {}) {
  const base = fs.mkdtempSync(path.join(os.tmpdir(), 'permission-scope-'));
  t.after(() => fs.rmSync(base, { recursive: true, force: true }));
  const cwd = path.join(base, 'project'), privateDir = path.join(base, 'private');
  fs.mkdirSync(cwd);
  const sessionId = 'permission_' + path.basename(base), adoptionId = 'adopt-' + 'b'.repeat(24);
  const charter = { revision: 1, objective: 'Synthetic permission regression', successCriteria: ['Retain authority boundaries'], constraints: [], nonGoals: [] };
  const charterHash = 'sha256:' + digest(JSON.stringify(charter));
  const confirmationHash = 'sha256:' + 'a'.repeat(64);
  const sessionFile = path.join(base, 'sessions', 'worker.jsonl');
  const provenance = {
    schema: 'pi-research-session.v1', parentSessionId: 'synthetic_parent',
    charterHash, adoptionId, workflowCwd: cwd, role: 'permission-inspector',
    stage: '2-experiment', task: scoped[0], spawnToken: 'synthetic_token', depth: 1,
    ...(inheritedReadOnly ? { readOnly: true } : {}),
  };
  write(sessionFile, { type: 'session', id: sessionId, cwd, version: 3 });
  write(sessionFile.replace(/\.jsonl$/, '.meta.json'), { cwd, pluginRefs: { 'res-workflow': {
    resWorkflow: { canonicalCwd: cwd, joinedAt: '2026-11-01T00:00:00Z', via: 'spawn' }, researchSession: provenance,
  } } });
  write(path.join(cwd, '.pi/research-loop/state.json'), { charter, stage: '2-experiment' });
  const ownerKey = JSON.stringify(['host', 'inert-operator']);
  const scope = path.join(privateDir, digest(ownerKey), digest(cwd));
  write(path.join(scope, 'adopted.json'), { confirmed: true, id: adoptionId, confirmationHash });
  write(path.join(scope, adoptionId + '.json'), { schema: 'pi-res-workflow-operation.v1', ownerKey, cwd,
    adoption: { id: adoptionId, cwd, status: 'confirmed' } });
  write(path.join(cwd, '.pi/research-loop/adoptions', adoptionId, 'confirmation.json'), {
    schema: 'pi-research-adoption-confirmation.v1', adoptionId, confirmationHash, charterHash, autoRun: false,
  });
  const ctx = { cwd, sessionManager: { getSessionId: () => sessionId, getSessionFile: () => sessionFile } };
  const hooks = new Map(), tools = new Map(), requests = [], spawns = [];
  const pi = {
    registerTool: tool => tools.set(tool.name, tool),
    on(name, handler) { if (!hooks.has(name)) hooks.set(name, []); hooks.get(name).push(handler); return () => {}; },
  };
  const contextOptions = { privateDir, env: { PI_SUBAGENT_CHILD: '1' } };
  const readContext = runtime => readWorkbenchRecordContext(runtime, contextOptions);
  assert.equal(readContext(ctx)?.researchSession?.readOnly, inheritedReadOnly);
  const snapshot = { status: 'ok', collaborator: true, decisionRequired: false, childrenPending: false,
    declaredTasks: 0, plans: [], assignment: { status: 'running' } };
  registerWorkbenchContext(pi, contextOptions);
  registerWorkbenchSessionTool(pi, { readContext, resolveAuth: () => ({ baseUrl: 'http://127.0.0.1:1', token: 'synthetic-unused' }),
    requestId: () => 'synthetic_request', fetchImpl: async (_url, options) => {
      spawns.push(JSON.parse(options.body));
      return { ok: true, headers: { get: () => null }, text: async () => JSON.stringify({
        status: 'spawned', spawnToken: 'fake_token', role: 'inspector', stage: '2-experiment', workflowCwd: cwd,
      }) };
    } });
  registerWorkbenchDispatchTool(pi, { readContext, request: async (_ctx, body) => { requests.push(body); return snapshot; } });
  registerDelegationPolicy(pi, { isJoined: () => !!readContext(ctx), bulkThreshold: 1 });
  async function emit(name, event) {
    const results = [];
    for (const handler of hooks.get(name) ?? []) results.push(await handler(event, ctx));
    return results;
  }
  async function prompt(text, messageType = 'user') {
    const event = { type: 'before_agent_start', messageType, prompt: text,
      systemPromptOptions: { cwd, selectedTools: ['research_session', 'research_dispatch'], sections: {} } };
    await emit('before_agent_start', event);
    return event.systemPromptOptions.sections[WORKBENCH_CONTEXT_SECTION];
  }
  const input = (text, source = 'interactive') => emit('input', { type: 'input', source, text });
  const gate = async (toolName = 'bash', toolInput = {}) => {
    const results = await emit('tool_call', { toolName, input: toolInput });
    return results.find(row => row?.block === true);
  };
  const dispatch = async () => {
    const value = await tools.get('research_dispatch').execute('test', { action: 'delegate', planId: 'synthetic_plan', task: 'synthetic', stage: '2-experiment' }, undefined, undefined, ctx);
    return { value, body: requests.at(-1) };
  };
  const spawn = async (extra = {}) => {
    const value = await tools.get('research_session').execute('test', { role: 'inspector', task: 'Synthetic only; never actually spawned', stage: '2-experiment', ...extra }, undefined, undefined, ctx);
    return { value, body: spawns.at(-1) };
  };
  async function nudge() {
    await emit('tool_execution_end', { toolName: 'read' });
    return (await emit('context', { messages: [] })).find(value => value?.messages)?.messages.at(-1)?.content;
  }
  const guardedSpawn = async () => {
    const blocked = await gate('research_session', { role: 'inspector', task: 'Synthetic only', stage: '2-experiment' });
    return blocked ? { blocked } : spawn();
  };
  return { ctx, provenance, prompt, input, gate, dispatch, spawn, guardedSpawn, spawnCount: () => spawns.length, nudge };
}

test('real installed context/session/dispatch hooks do not propagate object protection as global read-only', async t => {
  const f = fixture(t);
  const text = await f.prompt(buildResearchSessionPrompt(f.provenance));
  assert.doesNotMatch(text, /READ-ONLY MODE:/);
  assert.equal(await f.gate(), undefined);
  assert.equal((await f.dispatch()).body.readOnly, undefined);
  assert.equal((await f.spawn()).body.readOnly, undefined);
  assert.equal(await f.nudge(), undefined);
});

test('startup and generated follow-ups can tighten but cannot clear real user limits', async t => {
  const f = fixture(t);
  await f.input('Do not write any files.');
  const startup = buildResearchSessionPrompt({ ...f.provenance, task: 'You may edit control; original data read-only.' });
  await f.input(startup, 'rpc');
  const text = await f.prompt(startup);
  assert.match(text, /READ-ONLY MODE:/);
  assert.equal((await f.gate()).block, true);
  assert.equal((await f.dispatch()).body.readOnly, true);
  assert.equal((await f.spawn()).body.readOnly, true);
  await f.input('You may edit control.', 'extension');
  await f.prompt('Continue checking.');
  assert.equal((await f.gate()).block, true);
  assert.equal(await f.nudge(), undefined);
});

